"""
Starfallen entity model generator.

Each model is defined once here (parts, cubes, pivots, rotations, paint styles). The script
emits the Java LayerDefinition ("*Geometry.java") and paints UV-exact textures for every cube,
plus a matching emissive "_glow" texture. Run from the repository root:

    python3 tools/modelgen.py
"""
