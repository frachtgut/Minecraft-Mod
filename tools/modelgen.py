def seer_palette(ctx):
    elite = ctx.p.get("elite", False)
    robe = [(58, 12, 22), (80, 18, 30), (104, 26, 38), (128, 36, 48)] if elite else [(16, 10, 40), (24, 15, 58), (33, 21, 76), (44, 28, 96)]
