def st_rock(ctx, core=False, head=False):
    fill_noise(ctx, ROCK, 0.3, face_light(ctx.face))
    cracks(ctx, max(1, ctx.w * ctx.h // 60), 6 + ctx.rng.randrange(6), (140, 50, 15), (255, 130, 35))
    if ctx.face == "top":
        for x in range(ctx.w):
            if ctx.rng.random() < 0.3:
                ctx.set(x, 0, (92, 78, 66))
    if core and ctx.face == "north":
        cx, cy = ctx.w // 2, ctx.h // 2 - 1
        for y in range(ctx.h):
            for x in range(ctx.w):
                d = math.hypot((x - cx) * 1.3, y - cy)
                if d < 3.2:
                    c = mix((255, 250, 210), (255, 150, 40), d / 3.2)
                    ctx.both(x, y, c)
        for k in range(4):
            ang = k * math.pi / 2 + ctx.rng.random() * 0.6
            x, y = cx, cy
            for step in range(8):
                x = int(round(cx + math.cos(ang) * step * 1.4))
                y = int(round(cy + math.sin(ang) * step))
                ctx.both(x, y, (255, 140, 40))
    if head and ctx.face == "north":
        ey = ctx.h // 2 - 1
        for dx in (-3, -2, 1, 2):
            ctx.both(ctx.w // 2 + dx, ey, (255, 210, 90))
        ctx.both(ctx.w // 2 - 3, ey - 1, (255, 170, 60))
        ctx.both(ctx.w // 2 + 2, ey - 1, (255, 170, 60))
        for dx in range(-2, 2):
            ctx.set(ctx.w // 2 + dx, ey - 2, (24, 18, 16))
        for dx in range(-2, 2):
            ctx.both(ctx.w // 2 + dx, ey + 4, (200, 80, 20))


