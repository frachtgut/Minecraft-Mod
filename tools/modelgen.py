FACES = ("top", "bottom", "west", "north", "east", "south")


def face_rects(c):
    u, v = c.uv
    w, h, d = (int(math.ceil(s)) for s in c.size)
    return {
        "top": (u + d, v, w, d),
        "bottom": (u + d + w, v, w, d),
        "west": (u, v + d, d, h),
        "north": (u + d, v + d, w, h),
        "east": (u + d + w, v + d, d, h),
        "south": (u + 2 * d + w, v + d, w, h),
    }


class Ctx:
    def __init__(self, base, glow, x, y, w, h, face, cube, rng, noise, params):
        self.base, self.glow = base, glow
        self.x0, self.y0, self.w, self.h = x, y, w, h
        self.face, self.cube, self.rng, self.noise, self.p = face, cube, rng, noise, params

    def set(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.base.set(self.x0 + x, self.y0 + y, c)

    def glow_set(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.glow.set(self.x0 + x, self.y0 + y, c)

    def both(self, x, y, c):
        self.set(x, y, c)
        self.glow_set(x, y, c)

    def n(self, x, y, scale=0.35, octaves=3):
        return self.noise.fbm((self.x0 + x) * scale, (self.y0 + y) * scale, octaves)


def fill_noise(ctx, colors, scale=0.35, light=1.0):
    for y in range(ctx.h):
        for x in range(ctx.w):
            t = ctx.n(x, y, scale) * 0.85 + ctx.rng.random() * 0.15
            ctx.set(x, y, shade(ramp(colors, t), light))


def face_light(face):
    return {"top": 1.12, "bottom": 0.7, "north": 1.0, "south": 0.9, "west": 0.95, "east": 0.95}[face]


def cracks(ctx, count, length, dim, bright):
    for _ in range(count):
        x, y = ctx.rng.randrange(max(1, ctx.w)), ctx.rng.randrange(max(1, ctx.h))
        for _ in range(length):
            ctx.set(x, y, dim)
            ctx.glow_set(x, y, bright)
            r = ctx.rng.random()
            if r < 0.45:
                x += ctx.rng.choice((-1, 1))
            elif r < 0.9:
                y += ctx.rng.choice((-1, 1))
            else:
                x += ctx.rng.choice((-1, 1))
                y += 1


def speckle(ctx, chance, color, glow=True):
    for y in range(ctx.h):
        for x in range(ctx.w):
            if ctx.rng.random() < chance:
                if glow:
                    ctx.both(x, y, color)
                else:
                    ctx.set(x, y, color)


