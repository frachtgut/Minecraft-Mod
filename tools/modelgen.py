class Cube:
    def __init__(self, origin, size, style, uv=None, inflate=0.0, mirror=False):
        self.origin = origin
        self.size = size
        self.style = style
        self.uv = uv
        self.inflate = inflate
        self.mirror = mirror


class Part:
    def __init__(self, name, pivot=(0, 0, 0), rot=(0, 0, 0), cubes=(), children=()):
        self.name = name
        self.pivot = pivot
        self.rot = rot
        self.cubes = list(cubes)
        self.children = list(children)


class Model:
    def __init__(self, cls, tex, parts, textures):
        self.cls = cls
        self.tex = tex
        self.parts = parts
        # textures: list of (file_name, style_overrides dict)
        self.textures = textures


def all_cubes(parts):
    for p in parts:
        for c in p.cubes:
            yield p, c
        yield from all_cubes(p.children)


def pack(model):
    """Shelf-pack every cube's UV footprint into the texture."""
    tw, th = model.tex
    cubes = [c for _, c in all_cubes(model.parts) if c.uv is None]
    order = sorted(cubes, key=lambda c: -(c.size[2] + c.size[1]))
    x = y = shelf = 0
    for c in order:
        w, h, d = c.size
        fw, fh = int(math.ceil(2 * (d + w))), int(math.ceil(d + h))
        if x + fw > tw:
            x = 0
            y += shelf
            shelf = 0
        if y + fh > th:
            raise SystemExit(f"{model.cls}: texture {tw}x{th} too small")
        c.uv = (x, y)
        x += fw
        shelf = max(shelf, fh)


def f(v):
    return f"{float(v)}F"


def emit_java(model):
    lines = []
    counter = [0]

    def emit_part(part, parent):
        var = f"p{counter[0]}"
        counter[0] += 1
        cubes = "CubeListBuilder.create()"
        for c in part.cubes:
            cubes += f".texOffs({c.uv[0]}, {c.uv[1]})"
            if c.mirror:
                cubes += ".mirror()"
            o, s = c.origin, c.size
            cubes += (f".addBox({f(o[0])}, {f(o[1])}, {f(o[2])}, {f(s[0])}, {f(s[1])}, {f(s[2])}, "
                      f"new CubeDeformation({f(c.inflate)}))")
            if c.mirror:
                cubes += ".mirror(false)"
        pv, rt = part.pivot, part.rot
        pose = f"PartPose.offsetAndRotation({f(pv[0])}, {f(pv[1])}, {f(pv[2])}, {f(rt[0])}, {f(rt[1])}, {f(rt[2])})"
        lines.append(f"        PartDefinition {var} = {parent}.addOrReplaceChild(\"{part.name}\", {cubes}, {pose});")
        for ch in part.children:
            emit_part(ch, var)

    for p in model.parts:
        emit_part(p, "root")
    body = "\n".join(lines)
    src = f"""package net.starfallen.client.model.gen;

import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.*;

/** Generated by tools/modelgen.py - edit the generator, not this file. */
@SuppressWarnings("unused")
public final class {model.cls}Geometry {{
    private {model.cls}Geometry() {{}}

    public static LayerDefinition create() {{
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
{body}
        return LayerDefinition.create(mesh, {model.tex[0]}, {model.tex[1]});
    }}
}}
"""
    os.makedirs(JAVA_DIR, exist_ok=True)
    with open(os.path.join(JAVA_DIR, f"{model.cls}Geometry.java"), "w") as fh:
        fh.write(src)


