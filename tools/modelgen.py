def st_robe(ctx, skirt=False, sleeve=False):
    robe, trim = seer_palette(ctx)
    for y in range(ctx.h):
        for x in range(ctx.w):
            fold = 0.85 + 0.2 * math.sin(x * 1.3 + ctx.n(x, y, 0.2) * 3)
            ctx.set(x, y, shade(ramp(robe, ctx.n(x, y, 0.3)), fold * face_light(ctx.face)))
    if ctx.face in ("north", "south", "east", "west"):
        if skirt or sleeve:
            for x in range(ctx.w):
                ctx.set(x, ctx.h - 1, trim)
                if sleeve:
                    ctx.set(x, ctx.h - 2, trim)
            if skirt:
                for x in range(ctx.w):
                    if x % 3 == 1:
                        ctx.both(x, ctx.h - 3, (120, 230, 255))
        if ctx.face == "north" and not sleeve:
            cx = ctx.w // 2
            for y in range(ctx.h):
                ctx.set(cx, y, trim)
                if skirt and y > 1:
                    ctx.set(cx - 1, y, shade(robe[0], 0.8))
            if not skirt:
                for y in range(2, ctx.h - 2, 3):
                    ctx.both(cx, y, (140, 235, 255))
                for x in range(ctx.w):
                    ctx.set(x, 0, trim)
    if sleeve and ctx.face == "bottom":
        for y in range(ctx.h):
            for x in range(ctx.w):
                ctx.set(x, y, (220, 205, 180) if 0 < x < ctx.w - 1 and 0 < y < ctx.h - 1 else robe[0])


