def paint(model, tex_name, params, seed):
    tw, th = model.tex
    base = Canvas(tw, th)
    glow = Canvas(tw, th)
    rng = random.Random(seed)
    noise = Noise(seed)
    for part, c in all_cubes(model.parts):
        style = STYLES[c.style]
        p = dict(params)
        if c.style == "teeth_up":
            p["upper"] = True
        if c.style == "ray_wing_r" or c.style == "ray_wing_l":
            p["left"] = c.style == "ray_wing_l"
        for face, (x, y, w, h) in face_rects(c).items():
            if w <= 0 or h <= 0:
                continue
            style(Ctx(base, glow, x, y, w, h, face, c, rng, noise, p))
    os.makedirs(TEX_DIR, exist_ok=True)
    base.save(os.path.join(TEX_DIR, f"{tex_name}.png"))
    if params.get("glow", True):
        glow.save(os.path.join(TEX_DIR, f"{tex_name}_glow.png"))


