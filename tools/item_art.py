def bow_pulling(stage):
    """Pulling variants: the string of light draws back and a star arrow appears."""
    rows = [list(r) for r in SPRITES["constellation_bow"][0]]
    glow = [list(r) for r in SPRITES["constellation_bow"][2]]
    for y in range(16):
        for x in range(9, 16):
            if rows[y][x] == "S":
                rows[y][x] = "."
            if glow[y][x] == "S":
                glow[y][x] = "."
    pull = 14 - stage * 2
    top, bottom, mid = 2, 13, 7
    for y in range(top, bottom + 1):
        t = abs(y - mid) / (mid - top)
        x = int(round(pull - (pull - 10) * t)) if pull > 10 else 10
        if 0 <= x < 16:
            rows[y][x] = "S"
            glow[y][x] = "S"
    # arrow of light
    for x in range(3, pull):
        rows[mid][x] = "c" if x > 3 else "C"
        glow[mid][x] = "c" if x > 3 else "C"
    return ["".join(r) for r in rows], ["".join(r) for r in glow]


for _i in range(3):
    _rows, _glow = bow_pulling(_i)
    sprite(f"constellation_bow_pulling_{_i}", SPRITES["constellation_bow"][1], _rows, _glow)

