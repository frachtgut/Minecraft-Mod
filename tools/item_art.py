def tool(name, template, palette, accents=(), accent_char="m"):
    rows = [list(r) for r in template]
    glow = [["."] * 16 for _ in range(16)]
    for x, y in accents:
        if rows[y][x] not in ".o":
            rows[y][x] = accent_char
            glow[y][x] = accent_char
    rows = ["".join(r) for r in rows]
    sprite(name, palette, rows, ["".join(r) for r in glow] if accents else None)


