def armor(prefix, palette, accent, gem_positions):
    for piece, template in (("helmet", HELMET), ("chestplate", CHEST), ("leggings", LEGS), ("boots", BOOTS)):
        rows = [list(r.ljust(16, ".")[:16]) for r in template]
        glow = [["."] * 16 for _ in range(16)]
        for (x, y) in gem_positions.get(piece, []):
            if rows[y][x] not in ".o":
                rows[y][x] = accent
                glow[y][x] = accent
        sprite(f"{prefix}_{piece}", palette, ["".join(r) for r in rows], ["".join(r) for r in glow])


