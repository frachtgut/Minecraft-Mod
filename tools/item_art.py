def pal(*dicts):
    out = {}
    for d in dicts:
        out.update(d)
    out["."] = None
    return out


# ------------------------------------------------------------------ sprites
# Each entry: name -> (rows, palette, glow_rows or None)

SPRITES = {}


def sprite(name, palette, rows, glow=None):
    assert len(rows) == 16, f"{name}: {len(rows)} rows"
    for r in rows:
        assert len(r) == 16, f"{name}: row '{r}' has {len(r)} cols"
    if glow is not None:
        assert len(glow) == 16 and all(len(r) == 16 for r in glow), name
    SPRITES[name] = (rows, palette, glow)


